// Tiny i18n layer: Spanish is the default locale, English and French are optional.
// Keys are flat strings; `{name}` placeholders are replaced with `vars.name`.

export const LOCALES = ['es', 'en', 'fr'];
export const DEFAULT_LOCALE = 'es';
export const LOCALE_STORAGE_KEY = 'cuotia.locale';

export function normalizeLocale(value) {
  if (LOCALES.includes(value)) return value;
  // Accept region-tagged values such as 'fr-FR' or 'en_US'.
  const base = typeof value === 'string' ? value.toLowerCase().split(/[-_]/)[0] : '';
  return LOCALES.includes(base) ? base : DEFAULT_LOCALE;
}

const INTL_LOCALES = { es: 'es-CR', en: 'en-US', fr: 'fr-FR' };

export function intlLocale(locale) {
  return INTL_LOCALES[normalizeLocale(locale)];
}

