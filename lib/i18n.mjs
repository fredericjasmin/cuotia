export const dictionaries = { es, en };

export function hasMessage(key) {
  return Object.hasOwn(en, key) || Object.hasOwn(es, key);
}

export function translate(locale, key, vars) {
  const dictionary = dictionaries[normalizeLocale(locale)];
  const template = dictionary[key] ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) => {
    if (!Object.hasOwn(vars, name)) return match;
    const value = vars[name];
    if (typeof value === 'number') return value.toLocaleString(intlLocale(locale), { maximumFractionDigits: 7 });
    return String(value ?? '');
  });
}

// Errors thrown by lib code carry an i18n key so the UI can show them in the
// active language. The English text stays as Error.message for logs and tests.
export function localizedError(key, vars, extra) {
  const error = new Error(translate('en', key, vars));
  error.i18nKey = key;
  if (vars) error.i18nVars = vars;
  if (extra) Object.assign(error, extra);
  return error;
}
