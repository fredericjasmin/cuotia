// Writes lib/cuotia-spec.mjs: the Cuotia contract interface, so the app does not download the
// contract from the RPC (about 5 s) every time it reads it. Run after changing the contract:
//   npm run spec
import { readFileSync, writeFileSync } from 'node:fs';
import { contract } from '@stellar/stellar-sdk';

const wasmPath = new URL('../contracts/cuotia-v3/target/wasm32v1-none/release/cuotia_contract_v3.wasm', import.meta.url);
const spec = contract.Spec.fromWasm(readFileSync(wasmPath));
const entries = spec.entries.map((entry) => entry.toXDR('base64'));
const source = `// Generated by scripts/export-contract-spec.mjs from the Cuotia contract. Do not edit by hand:
// rebuild the contract and run \`npm run spec\`.
export const CUOTIA_SPEC_ENTRIES = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(new URL('../lib/cuotia-spec.mjs', import.meta.url), source);
console.log(`lib/cuotia-spec.mjs: ${entries.length} entries, ${spec.funcs().length} functions`);
